const MAX_LINKS = 30;

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const code = (text: string) => (text.includes("`") ? `\`\` ${text} \`\`` : `\`${text}\``);

/** A ticket-ready Markdown report of the analysis. */
export function reportMarkdown(input: ReportInput): string {
  const { email, report, file, generatedAt } = input;
  const locale = input.locale ?? "en";
  const l = L[locale];
  const safe = (text: string) => (input.defang ? defangText(text) : text);
  const headers = report.headers;
  const from = headers.sender.from;
  const out: string[] = [];

  out.push(`# ${l.title} — ${headers.subject || l.noSubject}`, "");
  out.push(`**${l.verdict}** ${BAND_LABEL[report.score.band][locale]} — ${l.score} ${report.score.score}/100`);
  out.push(`**${l.analysed}** ${formatUtc(generatedAt)} ${l.analysedWith}`);
  out.push(`**${l.file}** ${file.name} (${formatSize(file.size, locale)})`, "");
  out.push(`| ${l.field} | ${l.value} |`, "|---|---|");
  out.push(`| ${l.from} | ${cell(safe(from ? `${from.name ? `${from.name} ` : ""}<${from.address}>` : "—"))} |`);
  out.push(`| ${l.to} | ${cell(safe(decodeEncodedWords(getHeader(email.headers, "to") ?? "—")))} |`);
  out.push(`| ${l.date} | ${headers.date ? formatUtc(headers.date) : "—"} |`);
  out.push(`| ${l.subject} | ${cell(headers.subject || "—")} |`, "");

  out.push(`## ${l.findings} (${report.findings.length})`, "");
  if (report.findings.length === 0) out.push(l.noFinding);
  report.findings.forEach((finding, i) => {
    out.push(`${i + 1}. **${finding.title[locale]}** — ${l.severity[finding.severity]}, +${finding.weight}`);
    out.push(`   ${finding.explanation[locale]}`);
    for (const line of finding.evidence) out.push(`   - ${code(safe(line))}`);
  });
  out.push("");
  if (report.score.categories.length > 0) {
    out.push(`${l.categoryScore} ${report.score.categories.map((c) => `${c.category} ${c.points}/${c.cap}`).join(", ")}.`, "");
  }

  out.push(`## ${l.authentication}`, "");
  if (headers.auth.entries.length === 0) {
    out.push(l.noAuth);
  } else {
    const note = headers.auth.source ? (AUTH_SOURCE_NOTE[headers.auth.source]?.[locale] ?? null) : null;
    out.push(`${l.recordedBy} ${code(safe(headers.auth.recordedBy ?? l.unknown))}${note ? `, ${note}` : ""}.`, "");
    out.push(`| ${l.method} | ${l.result} | ${l.details} |`, "|---|---|---|");
    for (const entry of headers.auth.entries) out.push(`| ${entry.method} | ${entry.result} | ${cell(safe(entryDetails(entry)))} |`);
  }
  for (const check of report.dkim) {
    const verdict = check.result === "match" ? l.dkimMatch : check.result === "mismatch" ? l.dkimMismatch : l.dkimUnchecked;
    out.push("", `${l.dkimBody} d=${safe(check.signature.domain)}${locale === "fr" ? " " : ""}: ${verdict}.`);
  }
  out.push("");

  out.push(`## ${l.relay}`, "");
  if (headers.hops.length === 0) {
    out.push(l.noReceived);
  } else {
    out.push(`| # | ${l.time} | Δ | ${l.from} | IP | ${l.by} |`, "|---|---|---|---|---|---|");
    for (const hop of headers.hops) {
      out.push(
        `| ${hop.index} | ${hop.date ? formatTime(hop.date) : "—"} | ${formatDelay(hop.delay)} | ${cell(safe(hop.helo ?? hop.rdns ?? "—"))} | ${cell(safe(hop.ip ?? "—"))} | ${cell(safe(hop.by ?? "—"))} |`,
      );
    }
  }
  out.push("");

  const clickable = report.links.links.filter(isClickable);
  const flagged = clickable.filter((k) => k.url.flags.length > 0 || k.shownHost || k.hidden);
  out.push(`## ${l.links} (${clickable.length}, ${flagged.length} ${l.flagged})`, "");
  if (flagged.length === 0) out.push(l.noFlagged);
  for (const link of flagged.slice(0, MAX_LINKS)) {
    const notes = [
      link.shownHost ? `${l.shows} ${safe(link.shownHost)}` : null,
      ...link.url.flags.map((f) => (f === "lookalike" ? `${l.lookalikeOf} ${safe(link.url.lookalikeOf ?? "")}` : f)),
      link.hidden ? `${l.hidden} (${link.hidden[locale]})` : null,
      link.attachment ? `${l.in} ${link.attachment}` : null,
    ].filter(Boolean);
    out.push(`- ${code(safe(link.url.final ?? link.url.raw))} — ${notes.join(", ")}`);
  }
  out.push("");

  if (report.attachments.length > 0) {
    out.push(`## ${l.attachments}`, "", `| ${l.name} | ${l.detectedType} | ${l.size} | SHA-256 | ${l.flags} |`, "|---|---|---|---|---|");
    for (const a of report.attachments) {
      out.push(`| ${cell(a.visibleName)} | ${a.detected.label[locale]} | ${formatSize(a.size, locale)} | ${code(a.hashes.sha256)} | ${a.flags.join(", ") || "—"} |`);
    }
    out.push("");
  }

  out.push(`## ${l.indicators} (${report.iocs.length})`, "");
  for (const type of IOC_TYPES) {
    const list = report.iocs.filter((ioc) => ioc.type === type);
    if (list.length === 0) continue;
    out.push(`### ${l.ioc[type]}`, "");
    for (const ioc of list) out.push(`- ${code(input.defang ? defang(ioc.type, ioc.value) : ioc.value)} — ${ioc.sources.map((s) => s[locale]).join(", ")}`);
    out.push("");
  }

  out.push("---", "", l.warning, "", l.generated(input.defang));
  return out.join("\n");
}
